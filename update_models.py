#!/usr/bin/env python3
"""
Regenerates models.json from the public Hugging Face Hub API.
Standard library only. Run by the weekly GitHub Action, or by hand:

    python update_models.py

Safety: if the API fails or returns too little, the existing models.json is
left untouched and the script exits with an error.
"""
import json
import os
import re
import sys
import urllib.parse
import urllib.request

API = "https://huggingface.co/api/models"

# Publishers whose original (full-precision) releases we track.
AUTHORS = ["meta-llama", "Qwen", "google", "mistralai", "microsoft", "deepseek-ai"]

PER_AUTHOR_LIMIT = 100       # newest-popular repos fetched per publisher
MIN_DOWNLOADS = 20_000       # skip obscure repos
MIN_PARAMS_B = 0.3
MAX_PARAMS_B = 130.0
MIN_RESULT_COUNT = 10        # refuse to overwrite models.json with less than this

# Repo names containing these are quantized/derived copies, not base releases.
SKIP_WORDS = re.compile(
    r"gguf|awq|gptq|bnb|fp8|int4|int8|mlx|onnx|eagle|guard|embed|rerank|"
    r"vision|vl|audio|omni|ocr|tts|whisper|coder-.*-base|paligemma|shieldgemma|"
    r"bert|clip|siglip|image|diffusion|speech",
    re.I,
)
SIZE_IN_NAME = re.compile(r"(?<![\d.])(\d+(?:\.\d+)?)\s*[Bb](?![a-zA-Z])")


def fetch_author(author: str) -> list:
    params = [
        ("author", author),
        ("sort", "downloads"),
        ("direction", "-1"),
        ("limit", str(PER_AUTHOR_LIMIT)),
        ("expand[]", "safetensors"),
        ("expand[]", "downloads"),
        ("expand[]", "pipeline_tag"),
    ]
    url = f"{API}?{urllib.parse.urlencode(params)}"
    headers = {"User-Agent": "can-i-run-ai-model-updater"}
    token = os.environ.get("HF_TOKEN")
    if token:
        headers["Authorization"] = f"Bearer {token}"
    req = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.load(r)


def params_billions(item: dict):
    """Prefer exact total from safetensors metadata; fall back to the name."""
    st = item.get("safetensors") or {}
    total = st.get("total")
    if isinstance(total, (int, float)) and total > 0:
        return total / 1e9
    m = SIZE_IN_NAME.search(item.get("id", "").split("/")[-1])
    return float(m.group(1)) if m else None


def pretty_name(repo_id: str) -> str:
    name = repo_id.split("/")[-1]
    name = re.sub(r"[-_]?(instruct|chat|it)(?=$|[-_])", "", name, flags=re.I)
    name = re.sub(r"[-_ ]v\d+(\.\d+)*$", "", name)  # drop version tags like -v0.1
    return name.replace("-", " ").replace("_", " ").strip()


def build_models(items: list) -> list:
    """Pure function (easy to test): API items -> sorted unique model list."""
    best = {}
    for it in items:
        repo_id = it.get("id") or it.get("modelId") or ""
        if not repo_id:
            continue
        if it.get("pipeline_tag") not in (None, "text-generation", "image-text-to-text"):
            continue
        if (it.get("downloads") or 0) < MIN_DOWNLOADS:
            continue
        if SKIP_WORDS.search(repo_id.split("/")[-1]):
            continue
        p = params_billions(it)
        if p is None or not (MIN_PARAMS_B <= p <= MAX_PARAMS_B):
            continue
        name = pretty_name(repo_id)
        key = name.lower()
        # Instruct and base variants collapse to one row; keep the more downloaded.
        if key not in best or (it.get("downloads") or 0) > best[key][1]:
            best[key] = ({"name": name, "params_b": round(p, 1)}, it.get("downloads") or 0)
    models = [v[0] for v in best.values()]
    models.sort(key=lambda m: (m["params_b"], m["name"]))
    return models


def main() -> int:
    items = []
    for author in AUTHORS:
        try:
            got = fetch_author(author)
            print(f"{author}: {len(got)} repos")
            items.extend(got)
        except Exception as e:
            print(f"{author}: failed ({e})", file=sys.stderr)
    models = build_models(items)
    if len(models) < MIN_RESULT_COUNT:
        print(f"Only {len(models)} models found; keeping existing models.json.", file=sys.stderr)
        return 1
    out = {
        "_comment": "Auto-generated by update_models.py from the Hugging Face Hub API. Do not edit by hand.",
        "models": models,
    }
    path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "models.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(out, f, indent=2)
        f.write("\n")
    print(f"Wrote {len(models)} models to {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
